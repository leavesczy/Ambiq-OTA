    fun calcCrc32(len: Int, buf: ByteArray): Int {
        var crc = -1
        for (i in 0 until len) {
            val a = buf[i].toInt() and 0xFF
            val b = crc and 0xFF
            crc = CRC32_TABLE[a xor b] xor (crc ushr 8)
        }
        return crc.inv()
    }

